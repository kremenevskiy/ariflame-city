"""Адрес клиента для лимитов «с одного адреса» (contrib.py, media.py) — одно место на весь сервер.

Берём `request.client.host` — адрес, который uvicorn уже вычислил из заголовков прокси (`--proxy-headers`), а не левый
X-Forwarded-For из запроса. Левый адрес пишет сам клиент: с nginx `proxy_add_x_forwarded_for` (docs/DEPLOY.md) его
подделка остаётся первой в цепочке — лимит обходился сменой заголовка (аудит M-2, 24.11.2026).

Допущение выкладки — от него зависит, чей адрес тут окажется:
- uvicorn доверяет X-Forwarded-For только своему прокси: `--forwarded-allow-ips=<адрес Caddy или nginx перед ним>`.
  Тогда он идёт по цепочке справа налево и берёт первый адрес не из доверенных — настоящего клиента.
  Со `--forwarded-allow-ips=*` uvicorn верит всем и берёт ЛЕВЫЙ адрес из заголовка — подделку клиента; так нельзя.
- Прокси перед uvicorn либо пишет адрес клиента сам (nginx `proxy_set_header X-Forwarded-For $remote_addr`), либо
  дописывает его справа; цепочка из нескольких прокси (мост nginx → Caddy) — каждый следующий доверяет предыдущему
  (Caddy `trusted_proxies` с адресом моста), иначе Caddy пишет в заголовок адрес моста.
- Пока цепочка не настроена, у всех игроков за мостом один адрес: лимиты «с адреса» работают как общие. Это не строже,
  чем было: прежний разбор заголовка в проде давал тот же адрес моста.
"""
from __future__ import annotations


def client_ip(conn) -> str:
    """Request или WebSocket → адрес клиента (до 64 знаков); неизвестен — «?» (тогда все такие — один адрес)."""
    c = getattr(conn, "client", None)
    host = getattr(c, "host", None) if c is not None else None
    return (host or "")[:64] or "?"
